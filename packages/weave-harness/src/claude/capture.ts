import { homedir } from 'node:os';
import { access, mkdir, readFile, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { HARNESS_DIRS, HARNESS_EVENTS, INJECTABLE_EVENTS, type Harness } from '@weavecode/core';
import type { CaptureDeps, CaptureState, CaptureSurface } from '../driver.js';
import { CLAUDE_PROMPT_INBOX } from './prompt-inbox.js';

/**
 * weave 采集集成（hook-handler 脚本 + settings hooks 组）的 claude 实现——
 * tool-object-model §2.6 基石：user 档安装/启用面（跨项目采集，不依赖逐项目
 * init）。项目档的同一套组形/清扫判据也出自这里（cli settings-gen 委托），
 * 单源不留第二份。
 */

/**
 * hook-handler 脚本（跨端契约正文见脚本头注释）。version 只作脚本内的 weave
 * 版本标记（`@version weave@<version>`，weave 特性文件的覆写判据），由调用方
 * 传入——harness 包不依赖 server（版本常量在那边）。
 */
export function generateHookHandler(version: string): string {
  return `#!/usr/bin/env node
/**
 * weave hook-handler — collects Claude Code hook events into the global weave
 * data directory and renders locally-mirrored injections. No network, no
 * daemon dependency: daemon down = collection + static injection still work.
 *
 *   <configDir>/weave/hooks/inbox/<shard>.jsonl   events (append-only; daemon
 *       worker claims, ingests, then deletes)
 *   <configDir>/weave/hooks/mirror/<shard>.json   injection plan written by
 *       the daemon (static inject rules + pending session titles)
 *   <configDir>/weave/hooks/outbox/<shard>.jsonl  deferred injections (plugin
 *       output from the previous event; consumed by this script)
 *
 * shard = sha256(project token).slice(0,16). Dependency-free and designed to
 * NEVER block Claude Code: every code path is local file I/O and exits 0.
 * Directory names / shard algorithm / document shape are a cross-end contract
 * with the daemon side (weave-server src/hooks/mirror.ts + inbox-worker.ts).
 * Generated by weave — do not edit manually.
 * @version weave@${version}
 */
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');

const HOOK_GUARD_MS = 2000;
// Events that can carry additionalContext back via hook output (Claude Code
// contract; mirrors INJECTABLE_EVENTS.claude server-side).
const INJECTABLE_EVENTS = ['PostToolUse', 'UserPromptSubmit', 'SessionStart', 'Stop', 'SubagentStop'];
// Claude Code applies hookSpecificOutput.sessionTitle ONLY on these events
// (mirrors TITLE_EFFECTIVE_EVENTS.claude) — tool events record hook_success
// but drop the field (verified against 2.1.296).
const TITLE_EVENTS = ['SessionStart', 'UserPromptSubmit'];
const INBOX_MAX_BYTES = 4 * 1024 * 1024;
const INBOX_MAX_LINES = 1000;
const OUTBOX_MAX_LINES = 200;
const DEDUPE_WINDOW_MS = 60000;
const DISPATCH_MARKER = '<!--weave-dispatch-->';
const MIRROR_VERSION = 1;

// Ultimate safety net: never let this process outlive the hook window.
const GUARD = setTimeout(function () { process.exit(0); }, HOOK_GUARD_MS);
GUARD.unref();

function configDir() {
  if (process.platform === 'win32') {
    return process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming');
  }
  if (process.platform === 'darwin') {
    return path.join(os.homedir(), 'Library', 'Application Support');
  }
  return process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
}

function readProjectToken(projectDir) {
  try {
    var tok = fs.readFileSync(path.join(projectDir, '.weave', 'token'), 'utf8').trim();
    return tok || null;
  } catch {
    return null;
  }
}

function shardId(token) {
  return crypto.createHash('sha256').update(token).digest('hex').slice(0, 16);
}

function hooksDir() {
  return path.join(configDir(), 'weave', 'hooks');
}

// 会话自己的 inbox 直投凭据（Claude Code 在每个启用跨会话消息的会话里导出给
// 该会话的 hooks 与 Bash）：daemon 侧只放内存、不落库不进 UI —— 上报走 inbox
// 行的旁路字段（不进 report/payload）。
function messagingEnv() {
  var sock = process.env.${CLAUDE_PROMPT_INBOX.socketEnv};
  if (!sock) return null;
  return { socket: sock, token: process.env.${CLAUDE_PROMPT_INBOX.tokenEnv} || null };
}

function readStdin() {
  return new Promise(function (resolve) {
    var data = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', function (c) { data += c; });
    process.stdin.on('end', function () { resolve(data); });
    // Fallback if stdin never closes (e.g. manual invocation).
    setTimeout(function () { resolve(data); }, 500).unref();
  });
}

// ---- inbox (collection) ----

// Collection is best-effort: losing a single event must never break the hook.
function appendInbox(dir, token, report) {
  try {
    fs.mkdirSync(dir, { recursive: true });
    var file = path.join(dir, shardId(token) + '.jsonl');
    try {
      if (fs.statSync(file).size > INBOX_MAX_BYTES) trimFile(file, INBOX_MAX_LINES);
    } catch {}
    fs.appendFileSync(file, JSON.stringify({ v: 1, token: token, report: report, messaging: messagingEnv() }) + '\\n');
  } catch {}
}

// Backlog is bounded: past the cap keep only the newest lines (drop-oldest).
function trimFile(file, maxLines) {
  try {
    var lines = fs.readFileSync(file, 'utf8').split('\\n');
    var kept = [];
    for (var i = lines.length - 1; i >= 0 && kept.length < maxLines; i--) {
      if (lines[i].trim()) kept.unshift(lines[i]);
    }
    fs.writeFileSync(file, kept.join('\\n') + (kept.length ? '\\n' : ''));
  } catch {}
}

// ---- mirror (daemon-written injection plan; missing/corrupt = no injection) ----

function readMirror(dir, token) {
  try {
    var doc = JSON.parse(
      fs.readFileSync(path.join(dir, 'mirror', shardId(token) + '.json'), 'utf8')
    );
    return doc && doc.version === MIRROR_VERSION && Array.isArray(doc.rules) ? doc : null;
  } catch {
    return null;
  }
}

// ---- local rule matching (mirrors weave-server src/hooks/match.ts semantics) ----

const globCache = new Map();

function normalizePosix(p) {
  return p.replace(/\\\\/g, '/');
}

function escapeRegex(c) {
  return /[a-zA-Z0-9]/.test(c) ? c : '\\\\' + c;
}

function globToRegex(glob) {
  var cached = globCache.get(glob);
  if (cached) return cached;
  var re = '';
  for (var i = 0; i < glob.length; i++) {
    var c = glob[i];
    if (c === '*') {
      if (glob[i + 1] === '*') {
        i++;
        if (glob[i + 1] === '/') {
          i++;
          re += '(?:.*/)?';
        } else {
          re += '.*';
        }
      } else {
        re += '[^/]*';
      }
    } else if (c === '?') {
      re += '[^/]';
    } else {
      re += escapeRegex(c);
    }
  }
  var compiled = new RegExp('^' + re + '$', 'i');
  globCache.set(glob, compiled);
  return compiled;
}

function matchAnyGlob(filePath, globs) {
  var p = normalizePosix(filePath);
  for (var i = 0; i < globs.length; i++) {
    if (globToRegex(globs[i]).test(p)) return true;
  }
  return false;
}

function extractFilePath(toolInput) {
  if (typeof toolInput !== 'object' || toolInput === null) return null;
  var keys = ['file_path', 'notebook_path', 'filePath'];
  for (var i = 0; i < keys.length; i++) {
    var v = toolInput[keys[i]];
    if (typeof v === 'string' && v.length > 0) return v;
  }
  return null;
}

function renderTemplate(template, vars) {
  return template.replace(/\\{(\\w+)\\}/g, function (m, k) {
    var v = vars[k];
    return v === undefined || v === null ? m : String(v);
  });
}

// ---- 60s dedupe (same window as the server-side dispatcher): prevents an
// injected instruction from re-triggering itself through subsequent events ----

function dedupeStatePath(projectDir) {
  return path.join(projectDir, '.weave', 'dispatch-state.json');
}

function loadDedupe(projectDir, now) {
  var kept = {};
  try {
    var state = JSON.parse(fs.readFileSync(dedupeStatePath(projectDir), 'utf8')) || {};
    for (var k in state) {
      if (typeof state[k] === 'number' && now - state[k] < DEDUPE_WINDOW_MS) kept[k] = state[k];
    }
  } catch {}
  return kept;
}

function saveDedupe(projectDir, state) {
  try {
    var dir = path.join(projectDir, '.weave');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(dedupeStatePath(projectDir), JSON.stringify(state));
  } catch {}
}

// ---- outbox (deferred injections for this session; daemon-written) ----

function consumeOutbox(dir, token, sessionId) {
  var parts = [];
  try {
    var file = path.join(dir, 'outbox', shardId(token) + '.jsonl');
    var lines = fs.readFileSync(file, 'utf8').split('\\n');
    var kept = [];
    for (var i = 0; i < lines.length; i++) {
      var line = lines[i].trim();
      if (!line) continue;
      try {
        var entry = JSON.parse(line);
        if (sessionId && entry.sessionId === sessionId && typeof entry.text === 'string' && entry.text) {
          parts.push(entry.text);
        } else {
          kept.push(line);
        }
      } catch {}
    }
    if (parts.length > 0) {
      // Consumed lines are removed here; the daemon caps the file on append.
      var remaining = kept.slice(-OUTBOX_MAX_LINES);
      var tmp = file + '.tmp';
      fs.writeFileSync(tmp, remaining.length ? remaining.join('\\n') + '\\n' : '');
      fs.renameSync(tmp, file);
    }
  } catch {}
  return parts;
}

// ---- main ----

async function main() {
  var raw = await readStdin();
  var parsed = {};
  try { parsed = JSON.parse(raw); } catch {}

  var projectDir = process.env.CLAUDE_PROJECT_DIR || process.cwd();
  var token = readProjectToken(projectDir);
  // No token = project not registered — nothing to attribute the event to.
  if (!token) { process.exit(0); }

  var eventType = parsed.hook_event_name || parsed.event || 'unknown';
  var sessionId = parsed.session_id || parsed.sessionId || null;

  // Stop/SubagentStop 续跑守卫：宿主在「上一枪已经让 agent 继续了」之后，会带着
  // stop_hook_active=true 再问一次；此时必须闭嘴返回成功，否则会把"停止"一直判成
  // 被阻断，agent 空转（宿主连续 9 次后强制结束并告警）。Claude Code 的显式要求：
  // "For Stop/SubagentStop hooks, check stop_hook_active in the input and return
  // success while it's true." 判断提前（回执与下发共用同一条件），退出仍在
  // 采集之后——事件照收，只是不再注入。
  var silenced =
    (eventType === 'Stop' || eventType === 'SubagentStop') &&
    parsed.stop_hook_active === true;
  var injectable = INJECTABLE_EVENTS.indexOf(eventType) !== -1;

  // 改名交付回执：本事件确会把 pendingTitle 随响应下发——仅标题生效事件
  // （SessionStart/UserPromptSubmit，Claude Code 只在此应用 sessionTitle，
  // 工具事件下发即弃），且 injectable 未被静默、读得到 mirror。daemon 拿回执
  // 落定 pending_title——「改名待生效」徽标在生效当拍清除。非标题事件照常
  // 下发 additionalContext（注入不受影响）。
  var titleEvent = TITLE_EVENTS.indexOf(eventType) !== -1;
  var deliveredTitle = null;
  var mirror = injectable && !silenced ? readMirror(hooksDir(), token) : null;
  if (titleEvent && mirror && sessionId && mirror.pendingTitles) {
    var pending = mirror.pendingTitles[sessionId];
    if (typeof pending === 'string' && pending) deliveredTitle = pending;
  }

  // 1. Collection first: a kill mid-injection still leaves the event on disk.
  appendInbox(path.join(hooksDir(), 'inbox'), token, {
    source: 'claude',
    eventType: eventType,
    sessionId: sessionId,
    cwd: parsed.cwd || projectDir,
    payload: raw,
    deliveredTitle: deliveredTitle
  });

  if (silenced) { process.exit(0); }
  if (!injectable) { process.exit(0); }

  var parts = [];
  var toolName = parsed.tool_name || parsed.toolName || null;
  var filePath = extractFilePath(parsed.tool_input || parsed.toolInput || null);

  // 2. Locally mirrored inject rules (events → tool → globs; array order =
  // priority order, already sorted by the daemon when it wrote the mirror).
  if (mirror && mirror.rules.length > 0) {
    var now = Date.now();
    var dedupe = loadDedupe(projectDir, now);
    var dirty = false;
    for (var i = 0; i < mirror.rules.length; i++) {
      var rule = mirror.rules[i];
      if (!rule || !Array.isArray(rule.events) || rule.events.indexOf(eventType) === -1) continue;
      if (rule.tools && (!toolName || rule.tools.indexOf(toolName) === -1)) continue;
      if (rule.globs && rule.globs.length > 0) {
        if (!filePath || !matchAnyGlob(filePath, rule.globs)) continue;
      }
      var key = rule.id + ':' + (sessionId || '');
      if (dedupe[key] !== undefined) continue;
      dedupe[key] = now;
      dirty = true;
      parts.push(
        renderTemplate(String(rule.template || ''), {
          event: eventType,
          tool: toolName,
          file: filePath ? normalizePosix(filePath) : null,
          cwd: normalizePosix(parsed.cwd || projectDir),
          session: sessionId,
          project: mirror.project || null,
          rule: rule.name
        }) + '\\n' + DISPATCH_MARKER
      );
    }
    if (dirty) saveDedupe(projectDir, dedupe);
  }

  // 3. Deferred injections produced after this session's previous event.
  parts = parts.concat(consumeOutbox(hooksDir(), token, sessionId));

  // 4. Pending session rename (dashboard rename lands here via the mirror).
  var title = deliveredTitle;

  var specific = {};
  if (parts.length > 0) specific.additionalContext = parts.join('\\n\\n');
  if (typeof title === 'string' && title) specific.sessionTitle = title;
  if (Object.keys(specific).length > 0) {
    specific.hookEventName = eventType;
    process.stdout.write(JSON.stringify({ hookSpecificOutput: specific }));
  }
  process.exit(0);
}

main().catch(function () { process.exit(0); });
`;
}

// ---- settings hooks 组形与清扫判据（项目档与 user 档单源） ----

/**
 * weave 采集组的路径段判据：weave 的 hook 命令永远指向某个 `.claude/helpers/
 * hook-handler.cjs`（项目档与 user 档同形），命令含该段即 weave 组；用户
 * 自写脚本仅撞文件名（如 my-hook-handler.cjs）不匹配。
 */
export const HOOK_HANDLER_MARKER = '.claude/helpers/hook-handler.cjs';

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function toPosix(p: string): string {
  return p.replace(/\\/g, '/');
}

/** A hooks group is weave's when any of its commands invokes the hook-handler helper. */
export function groupIsWeave(group: unknown): boolean {
  if (!isPlainObject(group)) return false;
  const inner = group['hooks'];
  if (!Array.isArray(inner)) return false;
  return inner.some(
    (h) => isPlainObject(h) && typeof h['command'] === 'string' && toPosix(h['command']).includes(HOOK_HANDLER_MARKER),
  );
}

/**
 * 单事件的 weave 采集 hook 组（Claude Code 三层形：`hooks.<Event> = [{matcher:
 * '*', hooks: [{type, command}]}]`）。采集类（不可注入）事件标 `async: true`：
 * 宿主 fire-and-forget，不必等 hook 进程往返；口径与 INJECTABLE_EVENTS.claude
 * 同源（能注入的 = PostToolUse/UserPromptSubmit/SessionStart/Stop/SubagentStop，
 * 故 PreToolUse / Notification 异步）。
 */
export function captureHookGroup(event: string, helpersDir: string): Array<Record<string, unknown>> {
  const command = `node "${toPosix(helpersDir)}/hook-handler.cjs"`;
  const background = !(INJECTABLE_EVENTS.claude as readonly string[]).includes(event);
  return [
    {
      matcher: '*',
      hooks: [{ type: 'command' as const, command, ...(background ? { async: true } : {}) }],
    },
  ];
}

/**
 * hooks 子图清掉 weave 采集组：用户组不动；事件清空删键；非数组形状属用户，
 * 原样保留。返回清扫后的新子图；hooks 清空时 undefined（调用方删键）。
 */
export function sweepWeaveHookEvents(hooks: unknown): Record<string, unknown> | undefined {
  if (!isPlainObject(hooks)) return undefined;
  const out: Record<string, unknown> = {};
  for (const [event, groups] of Object.entries(hooks)) {
    if (!Array.isArray(groups)) {
      out[event] = groups;
      continue;
    }
    const userGroups = groups.filter((g) => !groupIsWeave(g));
    if (userGroups.length > 0) out[event] = userGroups;
  }
  return Object.keys(out).length > 0 ? out : undefined;
}

/** settings 里是否已有 weave 采集组（user 档 installed 判据）。 */
export function captureGroupsPresent(settings: unknown): boolean {
  if (!isPlainObject(settings)) return false;
  const hooks = settings['hooks'];
  if (!isPlainObject(hooks)) return false;
  return Object.values(hooks).some((groups) => Array.isArray(groups) && groups.some(groupIsWeave));
}

// ---- user 档采集安装/停用（§2.6 硬性要求） ----

function userSettingsFile(home: string): string {
  return path.join(home, HARNESS_DIRS.claude.userDir, 'settings.json');
}

function userHelpersDir(home: string): string {
  return path.join(home, HARNESS_DIRS.claude.userDir, 'helpers');
}

/** weave 特性文件的覆写判据（与 cli init 的 WEAVE_HELPER_MARKER 同判据）。 */
const WEAVE_HELPER_MARKER = '@version weave@';

async function pathExists(p: string): Promise<boolean> {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

/** 读 user settings；缺文件返回 {}；存在但不可解析/非对象抛错（无法合并进去就不碰）。 */
async function readUserSettings(file: string): Promise<Record<string, unknown>> {
  let raw: string;
  try {
    raw = await readFile(file, 'utf-8');
  } catch {
    return {};
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new Error(`user settings is not parseable JSON: ${file}`);
  }
  if (!isPlainObject(parsed)) throw new Error(`user settings is not a JSON object: ${file}`);
  return parsed;
}

/**
 * settings 文件里的 weave 采集组清扫（缺文件/坏文件 = 已达目的，不动）。
 * user 档停用与项目档去重共用。
 */
async function sweepSettingsFile(file: string): Promise<void> {
  let settings: Record<string, unknown>;
  try {
    settings = await readUserSettings(file);
  } catch {
    return;
  }
  const swept = sweepWeaveHookEvents(settings['hooks']);
  if (swept === undefined) delete settings['hooks'];
  else settings['hooks'] = swept;
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, JSON.stringify(settings, null, 2) + '\n', 'utf-8');
}

export async function readUserCapture(deps: CaptureDeps = {}): Promise<CaptureState> {
  const home = deps.home ?? homedir();
  const settings = await readUserSettings(userSettingsFile(home));
  return {
    installed: captureGroupsPresent(settings),
    helperPresent: await pathExists(path.join(userHelpersDir(home), 'hook-handler.cjs')),
  };
}

/**
 * user 档采集安装（幂等）：user 级 hook-handler 脚本 + `~/.claude/settings.json`
 * 的 weave 采集组（marker 清扫后并入，用户其余键永不动）。脚本锚点在 cwd/token，
 * 与落点无关——同一脚本项目档/user 档通用。
 */
export async function installUserCapture(deps: CaptureDeps & { version: string }): Promise<void> {
  const home = deps.home ?? homedir();
  const helpersDir = userHelpersDir(home);
  await mkdir(helpersDir, { recursive: true });
  await writeFile(
    path.join(helpersDir, 'hook-handler.cjs'),
    generateHookHandler(deps.version),
    'utf-8',
  );
  const file = userSettingsFile(home);
  const settings = await readUserSettings(file);
  const hooks = sweepWeaveHookEvents(settings['hooks']) ?? {};
  for (const event of HARNESS_EVENTS.claude) {
    const prev = hooks[event];
    hooks[event] = Array.isArray(prev)
      ? [...prev, ...captureHookGroup(event, helpersDir)]
      : captureHookGroup(event, helpersDir);
  }
  settings['hooks'] = hooks;
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, JSON.stringify(settings, null, 2) + '\n', 'utf-8');
}

/**
 * user 档采集停用（幂等）：清扫 user settings 的采集组 + 删 user 级脚本（带
 * weave 标记才删，用户文件不动）。
 */
export async function uninstallUserCapture(deps: CaptureDeps = {}): Promise<void> {
  const home = deps.home ?? homedir();
  await sweepSettingsFile(userSettingsFile(home));
  const script = path.join(userHelpersDir(home), 'hook-handler.cjs');
  try {
    const content = await readFile(script, 'utf-8');
    if (content.includes(WEAVE_HELPER_MARKER)) await unlink(script);
  } catch {
    // 缺文件即已达目的；无标记（用户文件）/读失败都不动
  }
}

/**
 * 项目档去重：user 档接管时清扫项目 `.claude/settings.json` 的 weave 采集组
 * （同一事件 user+project 双注册 = 双采集）。缺文件/坏文件 = 已达目的。
 */
export async function stripProjectCapture(projectPath: string): Promise<void> {
  await sweepSettingsFile(path.join(projectPath, HARNESS_DIRS.claude.projectDir, 'settings.json'));
}

export const CLAUDE_CAPTURE: CaptureSurface = {
  harness: 'claude' as Harness,
  readUserCapture: (deps) => readUserCapture(deps),
  installUserCapture: (deps) => installUserCapture(deps),
  uninstallUserCapture: (deps) => uninstallUserCapture(deps),
  stripProjectCapture,
};
