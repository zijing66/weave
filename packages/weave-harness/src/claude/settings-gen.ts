import type { InitComponents, HooksConfig, PlatformInfo } from '@weavecode/core';
import { captureHookGroup, sweepWeaveHookEvents } from './capture.js';

export interface SettingsGeneratorInput {
  components: InitComponents;
  hooks: HooksConfig;
  platform: PlatformInfo;
  /** Absolute path to the helpers directory in the target project */
  helpersDir: string;
}

/**
 * Path segments identifying weave's own helpers. weave always invokes them as
 * `<target>/.claude/helpers/<script>`, so a command is weave's when it carries
 * this segment — user scripts that merely share the file name (e.g.
 * `my-statusline.cjs`) are not matched.
 */
const WEAVE_STATUSLINE_MARKER = '.claude/helpers/statusline.cjs';

const WEAVE_SETTINGS_COMMENT = 'Generated by weave — do not edit manually';
export const WEAVE_PERMISSIONS_ALLOW = ['Bash(npx weave:*)', 'Bash(pnpm:*)', 'Bash(npm:*)'];
export const WEAVE_PERMISSIONS_DENY = ['Read(./.env)', 'Read(./.env.*)', 'Read(./secrets/*)'];

export function generateSettingsJson(input: SettingsGeneratorInput): Record<string, unknown> {
  const { components, hooks, platform, helpersDir } = input;

  const settings: Record<string, unknown> = {
    $comment: WEAVE_SETTINGS_COMMENT,
  };

  // Hooks — only when both settings and helpers are enabled
  if (components.helpers) {
    // 组形单源 harness 的 captureHookGroup：三层结构、命令表示法、采集类
    // （不可注入）事件 async fire-and-forget、注入事件同步回传。
    const hooksMap: Record<string, unknown> = {};
    if (hooks.preToolUse) hooksMap['PreToolUse'] = captureHookGroup('PreToolUse', helpersDir);
    if (hooks.postToolUse) hooksMap['PostToolUse'] = captureHookGroup('PostToolUse', helpersDir);
    if (hooks.userPromptSubmit) hooksMap['UserPromptSubmit'] = captureHookGroup('UserPromptSubmit', helpersDir);
    if (hooks.sessionStart) hooksMap['SessionStart'] = captureHookGroup('SessionStart', helpersDir);
    if (hooks.stop) hooksMap['Stop'] = captureHookGroup('Stop', helpersDir);
    if (hooks.stopFailure) hooksMap['StopFailure'] = captureHookGroup('StopFailure', helpersDir);
    if (hooks.subagentStop) hooksMap['SubagentStop'] = captureHookGroup('SubagentStop', helpersDir);
    if (hooks.subagentStart) hooksMap['SubagentStart'] = captureHookGroup('SubagentStart', helpersDir);
    if (hooks.notification) hooksMap['Notification'] = captureHookGroup('Notification', helpersDir);
    if (hooks.postToolUseFailure)
      hooksMap['PostToolUseFailure'] = captureHookGroup('PostToolUseFailure', helpersDir);
    if (hooks.permissionRequest)
      hooksMap['PermissionRequest'] = captureHookGroup('PermissionRequest', helpersDir);
    if (hooks.permissionDenied)
      hooksMap['PermissionDenied'] = captureHookGroup('PermissionDenied', helpersDir);
    if (hooks.preCompact) hooksMap['PreCompact'] = captureHookGroup('PreCompact', helpersDir);
    if (hooks.sessionEnd) hooksMap['SessionEnd'] = captureHookGroup('SessionEnd', helpersDir);
    // 模型切换确认：Pre 置位、Post 落定，成对登记（落定笔只服务于这一件事）。
    if (hooks.preModelSwitch) {
      hooksMap['PreModelSwitch'] = captureHookGroup('PreModelSwitch', helpersDir);
      hooksMap['PostModelSwitch'] = captureHookGroup('PostModelSwitch', helpersDir);
    }

    // 即使全被裁剪也写空对象：merge 语义靠「键存在」判定 helpers 是否启用，
    // 从而把 weave 的旧 hook 组整体清掉（weave 组 = 本次生成结果，空即清光）。
    settings['hooks'] = hooksMap;
  }

  // Permissions
  settings['permissions'] = {
    allow: [...WEAVE_PERMISSIONS_ALLOW],
    deny: [...WEAVE_PERMISSIONS_DENY],
  };

  // Env
  settings['env'] = { WEAVE_ENABLED: 'true' };

  // Status line — refreshInterval (seconds) lets Claude Code re-run the script
  // on a timer during idle periods; interaction-driven updates happen on top.
  // padding 0 keeps Claude Code from adding its own cell padding, so the
  // rendered line owns the full width (same convention as ccstatusline).
  if (components.helpers) {
    settings['statusLine'] = {
      type: 'command' as const,
      command: platform.os === 'windows' ? `node "${helpersDir}/statusline.cjs"` : 'node ' + helpersDir + '/statusline.cjs',
      padding: 0,
      refreshInterval: 30,
    };
  }

  return settings;
}

/**
 * Merge weave's generated settings into an existing user settings.json.
 *
 * Policy (weave init never overwrites user files):
 * - every existing key is preserved as-is (including unknown keys)
 * - weave entries are appended where missing
 * - weave's own hooks entries are REPLACED wholesale by this generation: first
 *   every group carrying the weave marker is dropped from all events (events
 *   no longer generated no longer linger), then the generated groups are
 *   appended. User-authored hook groups are never touched.
 * - statusLine pointing at `statusline.cjs` is refreshed in place
 * - user-authored statusLine, permissions, and env values are never touched
 *
 * Idempotent: merging the same `generated` twice yields the same result.
 */
export function mergeSettingsJson(
  existing: Record<string, unknown>,
  generated: Record<string, unknown>,
): Record<string, unknown> {
  const merged: Record<string, unknown> = { ...existing };

  // hooks — weave 组永远且仅等于本次生成结果（按 marker 清扫多余/过期组）
  const generatedHooks = generated['hooks'] as Record<string, unknown> | undefined;
  if (generatedHooks && typeof generatedHooks === 'object') {
    // 1) 清扫（单源 harness）：weave 组移除、事件清空删键、非数组用户形状不动。
    //    清扫后全空 → ?? {} 维持「hooks 键存在」（空即清光仍要落键）。
    const hooks = sweepWeaveHookEvents(
      isPlainObject(merged['hooks']) ? { ...(merged['hooks'] as Record<string, unknown>) } : {},
    ) ?? {};
    // 2) 并入本次生成的组（此时 prev 已无 weave 条目）。
    for (const [event, weaveGroups] of Object.entries(generatedHooks)) {
      const prev = hooks[event];
      if (prev === undefined) {
        hooks[event] = weaveGroups;
      } else if (Array.isArray(prev)) {
        hooks[event] = [...prev, ...(Array.isArray(weaveGroups) ? weaveGroups : [])];
      }
      // 非数组形状保持原样（用户数据）。
    }
    merged['hooks'] = hooks;
  }

  // statusLine — set when absent, or refresh when it already points at weave's script
  const prevStatusLine = merged['statusLine'];
  if (
    generated['statusLine'] &&
    (prevStatusLine === undefined || statusLineIsWeave(prevStatusLine))
  ) {
    merged['statusLine'] = generated['statusLine'];
  }

  // permissions — union (existing entries first, no duplicates)
  const generatedPerms = generated['permissions'] as Record<string, unknown> | undefined;
  if (generatedPerms && typeof generatedPerms === 'object') {
    const perms = isPlainObject(merged['permissions']) ? merged['permissions'] : {};
    for (const key of ['allow', 'deny'] as const) {
      const gen = generatedPerms[key];
      const prev = (perms as Record<string, unknown>)[key];
      if (Array.isArray(gen)) {
        (perms as Record<string, unknown>)[key] = unionLists(prev, gen);
      } else if (prev === undefined) {
        (perms as Record<string, unknown>)[key] = gen;
      }
    }
    merged['permissions'] = perms;
  }

  // env — fill missing keys only; existing values always win
  const generatedEnv = generated['env'] as Record<string, unknown> | undefined;
  if (generatedEnv && typeof generatedEnv === 'object') {
    const env = isPlainObject(merged['env']) ? merged['env'] : {};
    for (const [k, v] of Object.entries(generatedEnv)) {
      if ((env as Record<string, unknown>)[k] === undefined) {
        (env as Record<string, unknown>)[k] = v;
      }
    }
    merged['env'] = env;
  }

  return merged;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function statusLineIsWeave(statusLine: unknown): boolean {
  if (!isPlainObject(statusLine)) return false;
  const command = statusLine['command'];
  return typeof command === 'string' && commandIsWeave(command, WEAVE_STATUSLINE_MARKER);
}

/** Normalize separators so the marker matches on both Windows and POSIX paths. */
function commandIsWeave(command: string, marker: string): boolean {
  return command.replace(/\\/g, '/').includes(marker);
}

/** Union of two list-shaped values; existing entries keep their order and win. */
function unionLists(prev: unknown, next: unknown[]): unknown[] {
  if (!Array.isArray(prev)) return [...next];
  return [...prev, ...next.filter((x) => !prev.includes(x))];
}

/**
 * uninstall 用的剥除：把 merge 的加法原样减回去。weave 的 hook 组、weave 的
 * statusLine、weave 写入的默认 permissions/env 条目与 $comment 一并移除；
 * 用户自己的键（含 weave 之外的一切）永远不动。返回剩余 settings——键全空
 * 时为空对象，调用方据此删文件。
 */
export function stripWeaveSettings(existing: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = { ...existing };

  // hooks — 清扫（单源 harness）：weave 组移除、事件清空删键；hooks 清空删键。
  if (isPlainObject(out['hooks'])) {
    const hooks = sweepWeaveHookEvents(out['hooks'] as Record<string, unknown>);
    if (hooks) out['hooks'] = hooks;
    else delete out['hooks'];
  }

  // statusLine — 只删指向 weave statusline.cjs 的
  if (statusLineIsWeave(out['statusLine'])) delete out['statusLine'];

  // permissions — 减去 weave 默认条目；allow/deny 减空删键；permissions 清空删键
  if (isPlainObject(out['permissions'])) {
    const perms: Record<string, unknown> = { ...(out['permissions'] as Record<string, unknown>) };
    const subtract = (key: 'allow' | 'deny', defaults: string[]): void => {
      const prev = perms[key];
      if (!Array.isArray(prev)) return;
      const kept = prev.filter((x) => !defaults.includes(x as string));
      if (kept.length > 0) perms[key] = kept;
      else delete perms[key];
    };
    subtract('allow', WEAVE_PERMISSIONS_ALLOW);
    subtract('deny', WEAVE_PERMISSIONS_DENY);
    if (Object.keys(perms).length > 0) out['permissions'] = perms;
    else delete out['permissions'];
  }

  // env — 只删 WEAVE_ENABLED；清空删键
  if (isPlainObject(out['env'])) {
    const env: Record<string, unknown> = { ...(out['env'] as Record<string, unknown>) };
    delete env['WEAVE_ENABLED'];
    if (Object.keys(env).length > 0) out['env'] = env;
    else delete out['env'];
  }

  if (out['$comment'] === WEAVE_SETTINGS_COMMENT) delete out['$comment'];
  return out;
}
