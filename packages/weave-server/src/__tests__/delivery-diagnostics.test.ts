import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import type { Server } from 'node:http';
import type { DatabaseSync } from 'node:sqlite';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openDatabase } from '../db/db.js';
import { ProjectRepository } from '../repositories/projects.js';
import { HookEventRepository } from '../repositories/hook-events.js';
import { SessionRepository } from '../repositories/sessions.js';
import { createWeaveServer } from '../daemon/server.js';
import { setDaemonSettingsDb } from '../daemon/settings.js';
import { MessageDeliverer } from '../hooks/message-deliverer.js';
import { HookEventBus } from '../hooks/bus.js';

/**
 * 路由面：GET /messaging/diagnostics（投递诊断）。
 *
 * 判据是「这台机器/这条会话的三条通道现在能不能投」——本测试造的就是那个失败现场：
 * 项目 hook 脚本是旧版 weave 生成的（不上报直投凭据）、终端非 wezterm（无文本注入
 * 后端）、注册表里没有 peer name → 三层全灭、消息只能压队列。
 */

/** 旧版生成物：带 weave 标记（weave 认它是自己的）但不含凭据上报。 */
const OLD_HOOK_SCRIPT =
  '// Generated by weave — do not edit manually.\n// @version weave@0.0.1\n\'use strict\';\n';

const LIVE = 'sess-diag-live';
const DEAD = 'sess-diag-dead';

let db: DatabaseSync;
let server: Server;
let port: number;
let projectDir: string;
let fakeHome: string;
let origHome: string | undefined;
let origProfile: string | undefined;
let projectId: number;
let deliverer: MessageDeliverer;
let hooksDir: string;

const get = (p: string) => fetch(`http://127.0.0.1:${port}/api${p}`);
const json = async (p: string) => (await get(p)).json() as Promise<Record<string, never>>;

beforeAll(async () => {
  origHome = process.env.HOME;
  origProfile = process.env.USERPROFILE;
  fakeHome = mkdtempSync(join(tmpdir(), 'weave-diag-home-'));
  projectDir = mkdtempSync(join(tmpdir(), 'weave-diag-proj-'));
  // user 档隔离：本机没装过 user 档采集 → 生效分支 = 项目档（判据可预期）
  process.env.HOME = fakeHome;
  process.env.USERPROFILE = fakeHome;
  mkdirSync(join(projectDir, '.claude', 'helpers'), { recursive: true });
  writeFileSync(join(projectDir, '.claude', 'helpers', 'hook-handler.cjs'), OLD_HOOK_SCRIPT);

  db = openDatabase(':memory:');
  const projects = new ProjectRepository(db);
  const hookEvents = new HookEventRepository(db);
  const sessions = new SessionRepository(db);
  setDaemonSettingsDb(db);
  projectId = projects.register({ path: projectDir, name: 'diag', token: 'tok-diag', source: 'init' }).id;

  // 活着的会话：刚收到 UserPromptSubmit（harness 判据取自最新事件；豁免窗内不判死）
  sessions.touch(LIVE, projectId);
  hookEvents.insert({
    projectId,
    source: 'claude',
    eventType: 'UserPromptSubmit',
    sessionId: LIVE,
    payload: '{}',
  });
  // 已死的会话：同形状但 lastSeen 早过 90s 豁免窗 → pidAliveOf 判死
  sessions.touch(DEAD, projectId);
  hookEvents.insert({
    projectId,
    source: 'claude',
    eventType: 'UserPromptSubmit',
    sessionId: DEAD,
    payload: '{}',
  });
  db.prepare('UPDATE sessions SET last_seen_at = ? WHERE session_id = ?').run(
    new Date(Date.now() - 2 * 24 * 60 * 60_000).toISOString(),
    DEAD,
  );

  hooksDir = mkdtempSync(join(tmpdir(), 'weave-diag-hooks-'));
  deliverer = new MessageDeliverer({ sessions, projects, hookEvents, bus: new HookEventBus(), hooksDir });
  server = createWeaveServer({
    projects,
    port: 0,
    hookEvents,
    hookSessions: sessions,
    messageDeliverer: deliverer,
    hooksDir,
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  port = (server.address() as { port: number }).port;
});

afterAll(() => {
  server.close();
  setDaemonSettingsDb(null);
  db.close();
  process.env.HOME = origHome;
  process.env.USERPROFILE = origProfile;
  rmSync(fakeHome, { recursive: true, force: true });
  rmSync(projectDir, { recursive: true, force: true });
  rmSync(hooksDir, { recursive: true, force: true });
});

describe('daemon GET /messaging/diagnostics', () => {
  it('项目采集脚本读完：旧版生成物 = 在生效分支里、weave 拥有，但不上报凭据', async () => {
    const res = await get('/messaging/diagnostics?project=' + projectId);
    expect(res.status).toBe(200);
    const body = (await res.json()) as {
      daemon: { version: string; terminalPreset: string; terminalTextChannel: boolean };
      projects: Array<{ id: number; path: string; captures: unknown[] }>;
    };
    expect(body.daemon.version).toBeTruthy();
    expect(body.daemon.terminalTextChannel).toBe(false); // 测试装配不带终端通道
    const row = body.projects.find((p) => p.id === projectId)!;
    expect(row.path).toBe(projectDir);
    expect(row.captures[0]).toMatchObject({
      harness: 'claude',
      source: 'project',
      present: true,
      weaveOwned: true,
      generatedVersion: '0.0.1',
      reportsInbox: false,
      reportsPaneEnv: false,
    });
  });

  it('三层全灭的失败现场：通道矩阵 + 成因 + 修法码（且不重复报被上游解释掉的）', async () => {
    const body = (await json(`/messaging/diagnostics?project=${projectId}`)) as unknown as {
      sessions: Array<{
        sessionId: string;
        alive: boolean | null;
        eventCount: number;
        lastEventType: string | null;
        channels: Record<string, { status: string; reason: string | null }>;
        queue: { pending: number; stalled: boolean };
        reachable: boolean;
        hints: string[];
      }>;
    };
    const s = body.sessions.find((x) => x.sessionId === LIVE)!;
    expect(s.alive).toBeNull(); // 新会话豁免窗内判不动，不猜
    expect(s.eventCount).toBe(1);
    expect(s.lastEventType).toBe('UserPromptSubmit');
    expect(s.channels['inbox']).toEqual({ status: 'unavailable', reason: 'no-credentials' });
    expect(s.channels['relay']).toEqual({ status: 'unavailable', reason: 'no-peer-name' });
    expect(s.channels['terminal']).toEqual({ status: 'unavailable', reason: 'no-backend' });
    expect(s.queue).toEqual({ pending: 0, stalled: false });
    expect(s.reachable).toBe(false);
    expect(s.hints).toContain('hook-script-stale');
    expect(s.hints).toContain('no-peer-name');
    expect(s.hints).toContain('terminal-no-backend');
    // 脚本压根不上报凭据时，「这条会话没报凭据」不是独立成因——上游那条已经说清
    expect(s.hints).not.toContain('no-inbox-credentials');
    // 有事件就不该报「一条事件都没有」
    expect(s.hints).not.toContain('no-events');
  });

  it('默认只列活着的会话；?session= 能点名看死的（并给 not-running）', async () => {
    const all = (await json(`/messaging/diagnostics?project=${projectId}`)) as unknown as {
      sessions: Array<{ sessionId: string }>;
    };
    expect(all.sessions.map((s) => s.sessionId)).toEqual([LIVE]);

    const one = (await json(`/messaging/diagnostics?session=${DEAD}`)) as unknown as {
      sessions: Array<{ sessionId: string; alive: boolean | null; hints: string[] }>;
    };
    expect(one.sessions.map((s) => s.sessionId)).toEqual([DEAD]);
    expect(one.sessions[0]!.alive).toBe(false);
    expect(one.sessions[0]!.hints).toContain('not-running');
  });

  it('凭据只落在内存：有直投目标即 ready，且地址与 token 永不出现在响应里', async () => {
    const socket = `uds:${join(hooksDir, 'inbox.sock')}`;
    const token = 'secret-inbox-token-0123456789';
    deliverer.noteInboxSocket(LIVE, { socket, token });

    const res = await get(`/messaging/diagnostics?session=${LIVE}`);
    const raw = await res.text();
    expect(raw).not.toContain(token);
    expect(raw).not.toContain('inbox.sock');
    const body = JSON.parse(raw) as {
      sessions: Array<{
        channels: Record<string, { status: string; reason: string | null }>;
        reachable: boolean;
      }>;
    };
    expect(body.sessions[0]!.channels['inbox']).toEqual({ status: 'ready', reason: null });
    expect(body.sessions[0]!.reachable).toBe(true);

    deliverer.noteInboxSocket(LIVE, null); // 复原：凭据随会话走
  });

  it('未命中的路径不被吃掉（返回 false 走主链 404）', async () => {
    const res = await get('/messaging/diagnostics-typo');
    expect(res.status).toBe(404);
  });
});
