import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { mkdirSync, writeFileSync, unlinkSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { getAutoStartScriptPath, getDataDir } from '../db/paths.js';
import { readDaemonSettingsSync } from './settings.js';

/**
 * 开机自启动（默认关）：把 daemon 的重启命令注册进系统自启动项。
 *
 * - win32：HKCU Run 键 → wscript 跑一个藏在 weave 数据目录里的 VBS。绕一步
 *   VBS 是必须的：node 是控制台程序，Run 键直跑会在每次登录时常驻一个黑
 *   窗口；wscript 无窗口，VBS `Run …, 0` 再把子进程完全隐藏。
 * - darwin：~/Library/LaunchAgents plist（ProgramArguments 数组，无引号
 *   问题）+ launchctl load。
 * - linux：~/.config/autostart/*.desktop（XDG 自启动标准）。
 */

/** 自启动项标识（Run 键值名 / .desktop 文件名 / LaunchAgent label 后缀）。 */
const ENTRY_NAME = 'weave-daemon';
const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run';

export interface AutoStartDeps {
  /** 平台；默认 process.platform（测试覆盖）。 */
  platform?: NodeJS.Platform;
  /** weave 数据目录；默认 getDataDir()（测试指向 temp）。 */
  dataDir?: string;
  /** 用户主目录；默认 os.homedir()（测试指向 temp）。 */
  home?: string;
  /** 命令执行器；默认 spawnSync（测试 spy）。status 0 = 成功。 */
  run?: (command: string, args: string[]) => { status: number | null };
}

/**
 * 重启命令：按当前 daemon 进程的真实启动方式还原（node + execArgv + 入口
 * 脚本），不依赖 PATH 上的 weave——dev(tsx) 与安装版(node dist) 都成立。
 * 裸标识符 `tsx` 换成绝对路径：登录时的 cwd 任意，裸名会解析失败。
 */
export function relaunchArgs(): string[] {
  return [
    process.execPath,
    ...process.execArgv.map((arg) => {
      if (arg !== 'tsx' && !arg.startsWith('tsx/')) return arg;
      try {
        return fileURLToPath(import.meta.resolve(arg));
      } catch {
        return arg; // 解析不了就原样保留（best effort）
      }
    }),
    path.resolve(process.argv[1] ?? process.argv[0]),
  ];
}

interface ResolvedDeps {
  platform: NodeJS.Platform;
  dataDir: string;
  home: string;
  run: (command: string, args: string[]) => { status: number | null };
}

function resolveDeps(deps: AutoStartDeps): ResolvedDeps {
  return {
    platform: deps.platform ?? process.platform,
    dataDir: deps.dataDir ?? getDataDir(),
    home: deps.home ?? homedir(),
    run:
      deps.run ??
      ((command, args) => ({
        status: spawnSync(command, args, { stdio: 'ignore' }).status,
      })),
  };
}

/** Windows 路径不含 `"`，逐参数全量加引号即安全。 */
function quoteWinArgs(args: string[]): string {
  return args.map((a) => `"${a}"`).join(' ');
}

function enableWindows(deps: ResolvedDeps): void {
  const vbsPath = getAutoStartScriptPath(deps.dataDir);
  mkdirSync(path.dirname(vbsPath), { recursive: true });
  const cmdLine = quoteWinArgs(relaunchArgs());
  // VBS 字符串字面量里的 `"` 转义成 `""`。
  writeFileSync(
    vbsPath,
    `' Generated by weave — daemon auto-start. Do not edit.\n` +
      `CreateObject("WScript.Shell").Run "${cmdLine.replace(/"/g, '""')}", 0, False\n`,
  );
  deps.run('reg', [
    'add',
    RUN_KEY,
    '/v',
    ENTRY_NAME,
    '/t',
    'REG_SZ',
    '/d',
    `wscript.exe "${vbsPath}"`,
    '/f',
  ]);
}

function disableWindows(deps: ResolvedDeps): void {
  // 值不存在时 reg delete 报非 0——本来就是目标状态，忽略。
  deps.run('reg', ['delete', RUN_KEY, '/v', ENTRY_NAME, '/f']);
  try {
    unlinkSync(getAutoStartScriptPath(deps.dataDir));
  } catch {}
}

function plistXml(args: string[]): string {
  const esc = (s: string): string =>
    s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return (
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n` +
    `<plist version="1.0">\n<dict>\n` +
    `  <key>Label</key><string>com.weave.daemon</string>\n` +
    `  <key>ProgramArguments</key>\n  <array>\n` +
    args.map((a) => `    <string>${esc(a)}</string>`).join('\n') +
    `\n  </array>\n` +
    `  <key>RunAtLoad</key><true/>\n` +
    `</dict>\n</plist>\n`
  );
}

function enableMac(deps: ResolvedDeps): void {
  const plistPath = path.join(deps.home, 'Library', 'LaunchAgents', 'com.weave.daemon.plist');
  mkdirSync(path.dirname(plistPath), { recursive: true });
  writeFileSync(plistPath, plistXml(relaunchArgs()));
  // 先 unload 再 load：重注册时替换旧定义（首次 unload 会失败，忽略）。
  deps.run('launchctl', ['unload', plistPath]);
  deps.run('launchctl', ['load', plistPath]);
}

function disableMac(deps: ResolvedDeps): void {
  const plistPath = path.join(deps.home, 'Library', 'LaunchAgents', 'com.weave.daemon.plist');
  deps.run('launchctl', ['unload', plistPath]);
  try {
    unlinkSync(plistPath);
  } catch {}
}

/** .desktop Exec 只认双引号参数；带空格的路径需要包一层。 */
function quoteDesktopExec(args: string[]): string {
  return args.map((a) => (/[\s"]/.test(a) ? `"${a}"` : a)).join(' ');
}

function enableLinux(deps: ResolvedDeps): void {
  const desktopPath = path.join(deps.home, '.config', 'autostart', `${ENTRY_NAME}.desktop`);
  mkdirSync(path.dirname(desktopPath), { recursive: true });
  writeFileSync(
    desktopPath,
    [
      '[Desktop Entry]',
      'Type=Application',
      'Name=weave daemon',
      `Exec=${quoteDesktopExec(relaunchArgs())}`,
      'X-GNOME-Autostart-enabled=true',
      '',
    ].join('\n'),
  );
}

function disableLinux(deps: ResolvedDeps): void {
  try {
    unlinkSync(path.join(deps.home, '.config', 'autostart', `${ENTRY_NAME}.desktop`));
  } catch {}
}

/**
 * 注册/注销开机自启。所有平台路径共享；任何一步失败只 log 不抛——
 * 自启动是增强项，不能拖垮设置保存或 daemon 启动。
 */
export function applyLaunchOnLogin(enabled: boolean, deps: AutoStartDeps = {}): void {
  try {
    const d = resolveDeps(deps);
    if (d.platform === 'win32') {
      if (enabled) enableWindows(d);
      else disableWindows(d);
    } else if (d.platform === 'darwin') {
      if (enabled) enableMac(d);
      else disableMac(d);
    } else if (enabled) enableLinux(d);
    else disableLinux(d);
  } catch (e) {
    console.error(`[weave] auto-start ${enabled ? 'enable' : 'disable'} failed:`, e);
  }
}

/**
 * daemon 启动时对账：设置是唯一事实源——开着但系统项被外部清掉就重建，
 * 关着但有残留就清掉。两个方向都幂等（reg /f、unload+load、整文件重写）。
 */
export function syncLaunchOnLogin(deps: AutoStartDeps = {}): void {
  const startup = readDaemonSettingsSync().startup;
  applyLaunchOnLogin(startup?.launchOnLogin ?? false, deps);
}
