import { WEAVE_VERSION } from '@weave/server';

export function generateHookHandler(): string {
  return `#!/usr/bin/env node
/**
 * weave hook-handler — forwards Claude Code hook events to the weave daemon.
 *
 * Reads the hook JSON from stdin, resolves the project token (.weave/token)
 * and daemon port (global weave/daemon.json), then POSTs a report to
 * http://127.0.0.1:<port>/hooks and relays any {additionalContext,
 * sessionTitle} the daemon answers with (rule-driven session injection).
 * When the daemon is unreachable the report is spooled to .weave/spool.jsonl;
 * the next successful hook (or the daemon's startup sweep) flushes the
 * backlog via POST /hooks/batch.
 * Dependency-free and designed to NEVER block Claude Code: every code path
 * exits 0.
 * Generated by weave — do not edit manually.
 * @version weave@${WEAVE_VERSION}
 */
'use strict';

const fs = require('fs');
const path = require('path');
const http = require('http');
const os = require('os');

const HOOK_TIMEOUT_MS = 5000;
const FLUSH_TIMEOUT_MS = 30000;
// Spool/claim names are a cross-end contract with the daemon-side sweep
// (weave-server src/hooks/spool.ts) — the script is dependency-free, so the
// constants are duplicated on purpose.
const SPOOL_FILE = 'spool.jsonl';
const SPOOL_CLAIM = 'spool.claim.jsonl';
const SPOOL_MAX_BYTES = 4 * 1024 * 1024;
const SPOOL_MAX_LINES = 1000;
const FLUSH_CHUNK = 100;

// Ultimate safety net: never let this process outlive the hook window (the
// detached flusher child gets a longer leash — nothing is waiting on it).
const GUARD = setTimeout(
  function () { process.exit(0); },
  process.env.WEAVE_FLUSH === '1' ? FLUSH_TIMEOUT_MS : HOOK_TIMEOUT_MS
);
GUARD.unref();

function configDir() {
  if (process.platform === 'win32') {
    return process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming');
  }
  if (process.platform === 'darwin') {
    return path.join(os.homedir(), 'Library', 'Application Support');
  }
  return process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
}

function readDaemonPort() {
  try {
    var statePath = path.join(configDir(), 'weave', 'daemon.json');
    var state = JSON.parse(fs.readFileSync(statePath, 'utf8'));
    return state && state.port ? state.port : null;
  } catch {
    return null;
  }
}

function readProjectToken(projectDir) {
  try {
    var tok = fs.readFileSync(path.join(projectDir, '.weave', 'token'), 'utf8').trim();
    return tok || null;
  } catch {
    return null;
  }
}

function readStdin() {
  return new Promise(function (resolve) {
    var data = '';
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', function (c) { data += c; });
    process.stdin.on('end', function () { resolve(data); });
    // Fallback if stdin never closes (e.g. manual invocation).
    setTimeout(function () { resolve(data); }, 500).unref();
  });
}

function spoolPaths(projectDir) {
  var dir = path.join(projectDir, '.weave');
  return {
    dir: dir,
    spool: path.join(dir, SPOOL_FILE),
    claim: path.join(dir, SPOOL_CLAIM)
  };
}

// Daemon unreachable (no port / network failure): append the report to the
// project-local JSONL backlog instead of dropping it. HTTP-level rejections
// (4xx/5xx) do NOT spool — the server saw and rejected it, retrying is wrong.
function appendSpool(projectDir, report) {
  try {
    var p = spoolPaths(projectDir);
    fs.mkdirSync(p.dir, { recursive: true });
    try {
      if (fs.statSync(p.spool).size > SPOOL_MAX_BYTES) trimSpool(p.spool);
    } catch {}
    fs.appendFileSync(p.spool, JSON.stringify(report) + '\\n');
  } catch {}
}

// Backlog is bounded: past the byte cap keep only the newest lines.
function trimSpool(spoolPath) {
  try {
    var lines = fs.readFileSync(spoolPath, 'utf8').split('\\n');
    var kept = [];
    for (var i = lines.length - 1; i >= 0 && kept.length < SPOOL_MAX_LINES; i--) {
      if (lines[i].trim()) kept.unshift(lines[i]);
    }
    fs.writeFileSync(spoolPath, kept.join('\\n') + (kept.length ? '\\n' : ''));
  } catch {}
}

// A live delivery just succeeded — hand the offline backlog to a detached
// child (this script re-invoked with WEAVE_FLUSH=1) so the hook process itself
// never spends its window flushing. No backlog — no child spawned.
function maybeSpawnFlusher(projectDir) {
  try {
    var p = spoolPaths(projectDir);
    if (!fs.existsSync(p.spool) && !fs.existsSync(p.claim)) return;
    var child = require('child_process').spawn(process.execPath, [__filename], {
      detached: true,
      stdio: 'ignore',
      env: Object.assign({}, process.env, {
        WEAVE_FLUSH: '1',
        CLAUDE_PROJECT_DIR: projectDir
      })
    });
    child.unref();
  } catch {}
}

function postBatch(port, token, events) {
  return new Promise(function (resolve) {
    var body = JSON.stringify({ events: events });
    var req = http.request({
      hostname: '127.0.0.1',
      port: port,
      path: '/hooks/batch',
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'content-length': Buffer.byteLength(body),
        authorization: 'Bearer ' + token
      },
      timeout: HOOK_TIMEOUT_MS
    }, function (res) {
      res.resume();
      res.on('end', function () {
        resolve(res.statusCode >= 200 && res.statusCode < 300);
      });
    });
    req.on('error', function () { resolve(false); });
    req.on('timeout', function () { req.destroy(); resolve(false); });
    req.end(body);
  });
}

// WEAVE_FLUSH=1 mode: drain the project spool into the daemon in chunks.
// The rename-claim keeps concurrent flushers safe (hooks can run in
// parallel): only one process can rename a given spool into a claim, and late
// appends simply land in a fresh spool for the next round. Acknowledged
// chunks are removed from the claim as we go, so a crash mid-drain resumes
// where it stopped.
async function runFlush() {
  var projectDir = process.env.CLAUDE_PROJECT_DIR || process.cwd();
  var token = readProjectToken(projectDir);
  var port = readDaemonPort();
  if (!token || !port) { process.exit(0); }

  var p = spoolPaths(projectDir);
  // A leftover claim means the previous flush died mid-drain — finish it
  // before claiming more (renaming over an existing claim would clobber it).
  if (fs.existsSync(p.claim)) {
    await drainClaim(p.claim, port, token);
    if (fs.existsSync(p.claim)) { process.exit(0); }
  }
  if (fs.existsSync(p.spool)) {
    try { fs.renameSync(p.spool, p.claim); } catch { process.exit(0); }
    await drainClaim(p.claim, port, token);
  }
  process.exit(0);
}

async function drainClaim(claimPath, port, token) {
  var lines;
  try {
    lines = fs.readFileSync(claimPath, 'utf8').split('\\n');
  } catch { return; }
  var pending = [];
  for (var i = 0; i < lines.length; i++) {
    if (lines[i].trim()) pending.push(lines[i]);
  }
  while (pending.length > 0) {
    var chunk = pending.slice(0, FLUSH_CHUNK);
    var events = [];
    for (var j = 0; j < chunk.length; j++) {
      try { events.push(JSON.parse(chunk[j])); } catch {}
    }
    if (events.length === 0) {
      // Whole chunk corrupt — drop it and move on.
      pending = pending.slice(chunk.length);
      continue;
    }
    if (!(await postBatch(port, token, events))) break;
    pending = pending.slice(chunk.length);
    if (pending.length > 0) {
      try {
        fs.writeFileSync(claimPath, pending.join('\\n') + '\\n');
      } catch { break; }
    }
  }
  // Fully drained (or nothing usable left) — remove the claim so later hooks
  // do not keep spawning flushers for an empty file.
  if (pending.length === 0) {
    try { fs.unlinkSync(claimPath); } catch {}
  }
}

async function main() {
  var raw = await readStdin();
  var parsed = {};
  try { parsed = JSON.parse(raw); } catch {}

  var projectDir = process.env.CLAUDE_PROJECT_DIR || process.cwd();
  var token = readProjectToken(projectDir);
  // No token = project not registered — nothing to attribute the event to.
  if (!token) { process.exit(0); }

  var eventType = parsed.hook_event_name || parsed.event || 'unknown';
  var report = {
    source: 'claude',
    eventType: eventType,
    sessionId: parsed.session_id || null,
    cwd: parsed.cwd || projectDir,
    payload: raw
  };

  var port = readDaemonPort();
  // Daemon down: spool locally and let the next successful hook flush it.
  if (!port) { appendSpool(projectDir, report); process.exit(0); }

  var body = JSON.stringify(report);

  var req = http.request({
    hostname: '127.0.0.1',
    port: port,
    path: '/hooks',
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'content-length': Buffer.byteLength(body),
      authorization: 'Bearer ' + token
    },
    timeout: HOOK_TIMEOUT_MS
  }, function (res) {
    // The daemon answers with optional {additionalContext, sessionTitle}.
    // Relay them as hookSpecificOutput so a matched inject rule lands in the
    // session / renames it — the standard synchronous-hook output channel.
    // Any parse failure degrades to silent exit 0 (collection-only).
    var data = '';
    res.setEncoding('utf8');
    res.on('data', function (c) { data += c; });
    res.on('end', function () {
      try {
        var parsed = JSON.parse(data);
        var specific = {};
        if (parsed && typeof parsed.additionalContext === 'string' && parsed.additionalContext) {
          specific.additionalContext = parsed.additionalContext;
        }
        if (parsed && typeof parsed.sessionTitle === 'string' && parsed.sessionTitle) {
          specific.sessionTitle = parsed.sessionTitle;
        }
        if (Object.keys(specific).length > 0) {
          specific.hookEventName = eventType;
          process.stdout.write(JSON.stringify({ hookSpecificOutput: specific }));
        }
      } catch {}
      maybeSpawnFlusher(projectDir);
      process.exit(0);
    });
    // Response never completes — the GUARD above still fires.
  });
  req.on('error', function () { appendSpool(projectDir, report); process.exit(0); });
  req.on('timeout', function () { req.destroy(); appendSpool(projectDir, report); process.exit(0); });
  req.write(body);
  req.end();
}

if (process.env.WEAVE_FLUSH === '1') {
  runFlush().catch(function () { process.exit(0); });
} else {
  main().catch(function () { process.exit(0); });
}
`;
}

export function generateAutoMemoryHook(): string {
  return `#!/usr/bin/env node
/**
 * weave auto-memory-hook
 * Triggered on UserPromptSubmit to record user context.
 * @version weave@${WEAVE_VERSION}
 */
'use strict';

const chunks = [];
process.stdin.on('data', (c) => chunks.push(c));
process.stdin.on('end', () => {
  try {
    const input = JSON.parse(Buffer.concat(chunks).toString('utf-8'));
    process.stderr.write('[weave] auto-memory: session active\\n');
  } catch {
    // ignore
  }
  process.exit(0);
});
`;
}
